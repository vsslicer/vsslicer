/** Orca's catalogue with Bambu native names added, and the `bambu.` entries for keys Orca lacks. */
export const generateBambu = (
  orca: CatalogueFile,
  printConfig: string,
  preset: string,
): { orca: CatalogueFile; bambu: CatalogueFile } => {
  const own = generate(printConfig, preset, '').entries;
  const merged: CatalogueFile = structuredClone(orca);
  const entries: { [key: string]: CatalogueEntry } = {};
  for (const [key, e] of Object.entries(own)) {
    const rename = BAMBU_RENAMES[key];
    const target = key in merged.entries ? merged.entries[key]! : rename && merged.entries[rename.orca];
    if (target) {
      if (target.native.bambu) throw new Error(`${key}: ${rename?.orca ?? key} already has a Bambu name`);
      target.native.bambu = { key, ...(rename?.lossy ? { lossy: rename.lossy } : {}) };
      continue;
    }
    const line = /PrintConfig\.cpp:(\d+)/.exec(e.provenance!)![1]!;
    entries[`bambu.${key}`] = {
      ...e,
      native: { bambu: { key } },
      native_only: 'bambu',
      provenance: `Ported from BambuStudio@${BAMBU_COMMIT}:${PRINT_CONFIG}:${line}${e.provenance!.endsWith(')') ? ' (label generated from the key)' : ''}`,
    };
  }
  return { orca: merged, bambu: { notice: BAMBU_NOTICE, entries } };
};

