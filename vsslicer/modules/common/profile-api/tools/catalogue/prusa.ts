/** Value types that convert into another without loss (the target is wider). */
const WIDENS: { [from: string]: string[] } = {
  int: ['float'],
  float: ['float_or_percent'],
  percent: ['float_or_percent'],
  polygon: ['point'],
  string: ['gcode'],
  gcode: ['string'],
};
const owner = (target: string) => (target.startsWith('prusa.') ? 'PrusaSlicer' : 'Orca');
/** A `lossy` note when a value of type `from` does not fit the entry's type `to`. */
const typeLoss = (dialect: string, from: string | undefined, target: string, to: string): string | undefined =>
  !from || from === to || WIDENS[from]?.includes(to)
    ? undefined
    : from === 'percent' && to === 'float'
      ? `${dialect} percent (100%), ${owner(target)} ratio (1.0)`
      : `${dialect} ${from}, ${owner(target)} ${to}`;
const NOWHERE: Placement = { print: new Set(), filament: new Set(), printer: new Set(), perExtruder: new Set() };
/** The catalogue type of a definition, as toEntry gives it; SuperSlicer graphs are polygons. */
const typeOf = (d: Def, maps: Map<string, Map<string, string>>): string =>
  /^coGraphs?$/.test(d.co) ? 'polygon' : toEntry(d, NOWHERE, maps, '').type;

// ---- Hardware features (PrusaSlicer 3.0 `printer.`, `tool.`, `sheet.`, `feeder.` namespaces) ----

export interface Feature {
  ns: 'printer' | 'tool' | 'sheet' | 'feeder';
  key: string;
  file: string;
  line: number;
  default?: Value;
}
const NAMESPACES = ['printer', 'tool', 'sheet', 'feeder'] as const;
const isNs = (s: string): s is Feature['ns'] => (NAMESPACES as readonly string[]).includes(s);

/** The `features:` block of vendor.yaml's vendor document: `<ns>: <feature>: default: <v>`. */
export const vendorFeatures = (yaml: string, file = PINNED.prusa3.files.vendor): Feature[] => {
  const lines = yaml.split('\n');
  const out: Feature[] = [];
  const indent = (s: string) => s.length - s.trimStart().length;
  const scalar = (s: string): Value => {
    if (s === 'true' || s === 'false') return s === 'true';
    const n = Number(s);
    return s !== '' && Number.isFinite(n) ? n : s.replace(/^(["'])(.*)\1$/, '$2');
  };
  let i = lines.findIndex((l) => l.trimEnd() === 'features:');
  if (i < 0) throw new Error(`${file}: no features block`);
  let ns: Feature['ns'] | undefined;
  for (i++; i < lines.length; i++) {
    const raw = lines[i]!.replace(/\r$/, '');
    if (raw.trim() === '' || raw.trimStart().startsWith('#')) continue;
    const d = indent(raw);
    if (d === 0) break;
    const text = raw.trim();
    const colon = text.indexOf(':');
    if (colon < 0) continue;
    const name = text.slice(0, colon);
    const rest = text.slice(colon + 1).trim();
    if (d === 2) ns = isNs(name) ? name : undefined;
    else if (d === 4 && ns) out.push({ ns, key: name, file, line: i + 1 });
    else if (d === 6 && name === 'default' && out.length) out.at(-1)!.default = scalar(rest);
  }
  return out;
};

/** Built-in hardware values: `append_value(values, "printer.tool_count", ...)`, and `"feeder."` HwModel fields. */
export const builtinFeatures = (t: Token[], file = PINNED.prusa3.files.valueMap): Feature[] => {
  const out: Feature[] = [];
  for (let i = 0; i + 4 < t.length; i++) {
    if (!(t[i]!.v === 'append_value' && t[i + 1]!.v === '(' && t[i + 2]!.v === 'values' && t[i + 4]!.k === 'str'))
      continue;
    const s = t[i + 4]!.v;
    const dot = s.indexOf('.');
    const ns = s.slice(0, dot);
    if (dot < 0 || !isNs(ns)) continue;
    const line = t[i]!.line;
    if (dot === s.length - 1) {
      // A HwModel: its `model` and `base_model` fields (append_value(values, prefix, const HwModel&)).
      if (t[i + 6]?.v.startsWith('Domain') || t[i + 8]?.v === 'model' || t[i + 10]?.v === 'model')
        for (const key of ['model', 'base_model']) out.push({ ns, key, file, line });
    } else {
      // `append_value(values, "feeder.single_mode", false)`: a literal gives the type.
      const v = t[i + 6];
      const literal = t[i + 7]?.v === ')' && (v?.v === 'true' || v?.v === 'false') ? v.v === 'true' : undefined;
      out.push({ ns, key: s.slice(dot + 1), file, line, ...(literal !== undefined ? { default: literal } : {}) });
    }
  }
  return out;
};

// ---- SuperSlicer `.ui` layouts ----

export interface UiPlace {
  file: string;
  page: string;
  group: string;
  line: number;
}

/** Setting keys on a SuperSlicer `.ui` page, with the page and group they sit in. */
export const uiSettings = (text: string, file: string, known: (key: string) => boolean): Map<string, UiPlace> => {
  const out = new Map<string, UiPlace>();
  let page = '';
  let group = '';
  for (const [n, raw] of text.split('\n').entries()) {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) continue;
    const parts = line.split(':');
    if (parts[0] === 'page') {
      // page:Title:icon, or page:idx:Title:icon for per-extruder pages.
      page = parts[1] === 'idx' ? (parts[2] ?? '') : (parts[1] ?? '');
      continue;
    }
    if (parts[0] === 'group') {
      group = parts.at(-1)!;
      continue;
    }
    // `setting:opt$v:...:key` (a `script` setting is a virtual one), or a bare key on its own line.
    const key = parts[0] === 'setting' ? parts.at(-1)! : parts.length === 1 ? line : '';
    if (parts.includes('script') || !known(key) || out.has(key)) continue;
    out.set(key, { file, page, group, line: n + 1 });
  }
  return out;
};

// ---- Assignment ----

const unified = (prefix: string, key: string) => `${prefix}${key.replaceAll('-', '_')}`;

type Name = { key: string; lossy?: string; legacy?: boolean; pinned?: string };
/** Sets `entry.native[dialect]`; one native name per dialect, so a second, different one is an error. */
const setNative = (key: string, entry: CatalogueEntry, dialect: Dialect, name: Name) => {
  const had = entry.native[dialect] as Name | undefined;
  if (had && had.key !== name.key) throw new Error(`${key}: ${dialect} names ${had.key} and ${name.key}`);
  // The same name read twice (a 3.0 tool feature that is also a legacy key) is current unless both are legacy.
  const merged: Name = { ...had, ...name };
  if (!(had ?? name).legacy || !name.legacy) delete merged.legacy;
  entry.native[dialect] = merged;
};

const CPP_TYPES: { [cpp: string]: string } = {
  bool: 'coBool',
  int: 'coInt',
  'std::optional<int>': 'coInt',
  double: 'coFloat',
  'std::string': 'coString',
  EnumWrapper: 'coEnum',
  FloatOrPercentage: 'coFloatOrPercent',
  Percentage: 'coPercent',
  'std::vector<double>': 'coFloats',
  'std::vector<std::string>': 'coStrings',
  'std::vector<Vec2d>': 'coPoints',
};
const LOCATIONS: { [location: string]: keyof Omit<Placement, 'perExtruder'> } = {
  Print: 'print',
  Object: 'print',
  Volume: 'print',
  Project: 'print',
  Filament: 'filament',
  Printer: 'printer',
  Tool: 'printer',
};

/** Prusa 2.9 lists: the preset pages and the per-extruder keys. */
const prusaPlacement = (printConfig: Token[], preset: Token[], defs: Map<string, Def>): Placement => {
  const extruder = stringList(printConfig, 'm_extruder_option_keys');
  return {
    print: new Set(stringList(preset, 's_Preset_print_options')),
    filament: new Set(stringList(preset, 's_Preset_filament_options')),
    printer: new Set([
      ...stringList(preset, 's_Preset_machine_limits_options'),
      ...stringList(preset, 's_Preset_printer_options'),
      ...extruder,
      ...[...defs.keys()].filter((k) => /^machine_max_(feedrate|acceleration|jerk)_[xyze]$/.test(k)),
    ]),
    perExtruder: new Set(extruder),
  };
};

export interface PrusaCatalogues {
  orca: CatalogueFile;
  prusa: CatalogueFile;
  superslicer: CatalogueFile;
}

/** Orca's catalogue with Prusa 2.9, 3.0 and SuperSlicer names added, plus the `prusa.` and `superslicer.` entries. */
export const generatePrusa = (orca: CatalogueFile, src: Sources): PrusaCatalogues => {
  const merged: CatalogueFile = structuredClone(orca);
  const prusa: CatalogueFile = { notice: PRUSA_NOTICE, entries: {} };
  const superslicer: CatalogueFile = { notice: SUPERSLICER_NOTICE, entries: {} };
  const entry = (key: string): CatalogueEntry | undefined =>
    merged.entries[key] ?? prusa.entries[key] ?? superslicer.entries[key];
  const orcaTarget = (key: string) => (key in orca.entries ? key : undefined);

  // PrusaSlicer 2.9.
  const p = PINNED.prusa.files;
  const pTokens = tokenize(src.prusa.printConfig);
  const pDefs = extractDefs(pTokens);
  const pPlace = prusaPlacement(pTokens, tokenize(src.prusa.preset), pDefs);
  const pMaps = enumMaps(pTokens);
  /** Where each 2.9 key landed. */
  const of29 = new Map<string, string>();
  for (const k of Object.keys(PRUSA_RENAMES)) if (!pDefs.has(k)) throw new Error(`${k}: not a PrusaSlicer 2.9 FFF key`);
  for (const d of pDefs.values()) {
    const rename = PRUSA_RENAMES[d.key];
    const target = rename ? rename.to : orcaTarget(d.key);
    if (rename && !(rename.to in orca.entries))
      throw new Error(`${d.key}: rename target ${rename.to} is not an Orca key`);
    if (target) {
      const lossy = rename?.lossy ?? typeLoss('Prusa', typeOf(d, pMaps), target, merged.entries[target]!.type);
      setNative(target, merged.entries[target]!, 'prusa', { key: d.key, ...(lossy ? { lossy } : {}) });
      of29.set(d.key, target);
      continue;
    }
    const key = unified('prusa.', d.key);
    prusa.entries[key] = {
      ...toEntry(d, pPlace, pMaps, `Ported from PrusaSlicer@${PRUSA_COMMIT}:${p.printConfig}`),
      native: { prusa: { key: d.key } },
      native_only: 'prusa',
    };
    of29.set(d.key, key);
  }

  // PrusaSlicer 3.0: the domain definitions, the legacy 2.x copy it still loads, and the hardware features.
  const q = PINNED.prusa3.files;
  const domain = new Map<string, DomainDef & { file: string }>();
  for (const f of ['common', 'fdm'] as const)
    for (const [k, d] of extractDomain(tokenize(src.prusa3[f]))) domain.set(k, { ...d, file: q[f] });
  const legacyTokens = tokenize(src.prusa3.legacy);
  const legacy = extractDefs(legacyTokens);
  const legacyMaps = enumMaps(legacyTokens);
  const pin = { pinned: PRUSA3_PIN };
  const target3 = (key: string): string | undefined => PRUSA3_RENAMES[key]?.to ?? of29.get(key) ?? orcaTarget(key);
  const own3 = (key: string, d: Def, place: Placement, maps: Map<string, Map<string, string>>, file: string) => {
    const k = unified('prusa.', key);
    prusa.entries[k] = {
      ...toEntry(d, place, maps, `Ported from PrusaSlicer@${PRUSA3_COMMIT}:${file}`),
      native: {},
      native_only: 'prusa3',
    };
    return k;
  };
  for (const d of domain.values()) {
    const rename = PRUSA3_RENAMES[d.key];
    let target = target3(d.key);
    if (!target) {
      const co = CPP_TYPES[d.cppType];
      if (!co) throw new Error(`${d.key}: unknown type ${d.cppType}`);
      const list = LOCATIONS[d.location ?? ''] ?? 'print';
      const place: Placement = {
        print: new Set(),
        filament: new Set(),
        printer: new Set(),
        perExtruder: new Set(),
        [list]: new Set([d.key]),
      };
      target = own3(d.key, { ...d, co }, place, new Map(), d.file);
      if (d.category === 'Hidden') prusa.entries[target]!.hidden = true;
    }
    const co = CPP_TYPES[d.cppType];
    const lossy =
      rename?.lossy ??
      (of29.get(d.key) === target ? PRUSA_RENAMES[d.key]?.lossy : undefined) ??
      (co ? typeLoss('PrusaSlicer 3.0', typeOf({ ...d, co }, new Map()), target, entry(target)!.type) : undefined);
    setNative(target, entry(target)!, 'prusa3', { key: d.key, ...(lossy ? { lossy } : {}), ...pin });
  }
  const lPlace = prusaPlacement(legacyTokens, tokenize(src.prusa.preset), legacy);
  for (const d of legacy.values()) {
    if (domain.has(d.key)) continue;
    const target = target3(d.key) ?? own3(d.key, d, lPlace, legacyMaps, q.legacy);
    const lossy =
      (of29.get(d.key) === target ? PRUSA_RENAMES[d.key]?.lossy : undefined) ??
      typeLoss('PrusaSlicer 3.0', typeOf(d, legacyMaps), target, entry(target)!.type);
    setNative(target, entry(target)!, 'prusa3', { key: d.key, ...(lossy ? { lossy } : {}), legacy: true, ...pin });
  }
  const features = [...vendorFeatures(src.prusa3.vendor), ...builtinFeatures(tokenize(src.prusa3.valueMap))];
  const seen = new Set<string>();
  for (const f of features) {
    const id = `${f.ns}.${f.key}`;
    if (seen.has(id)) continue;
    seen.add(id);
    // A tool feature that 2.9 stores as a printer key (nozzle_diameter, nozzle_high_flow) takes that key's entry.
    let target = f.ns === 'tool' ? of29.get(f.key) : undefined;
    if (!target) {
      target = unified('prusa.', `hw_${f.ns}_${f.key}`);
      const type =
        typeof f.default === 'boolean'
          ? 'bool'
          : typeof f.default === 'number'
            ? 'float'
            : f.key.endsWith('_count')
              ? 'int'
              : 'string';
      prusa.entries[target] = {
        group: 'machine',
        home:
          f.ns === 'tool' ? 'nozzle' : f.ns === 'sheet' ? 'surface' : f.ns === 'feeder' ? 'feeder' : 'printer_model',
        type,
        ...(f.default !== undefined ? { default: f.default } : {}),
        label: `${f.ns[0]!.toUpperCase()}${f.ns.slice(1)} ${f.key.replace(/_/g, ' ')}`,
        native: {},
        hidden: true,
        native_only: 'prusa3',
        provenance: `Ported from PrusaSlicer@${PRUSA3_COMMIT}:${f.file}:${f.line} (label generated from the key)`,
      };
    }
    // 3.0 stores a feature under its namespaced name (`printer.tool_count`), which supersedes a legacy 2.x name of
    // the same entry (`nozzle_diameter`, still read as the `prusa` name).
    const e = entry(target)!;
    if ((e.native.prusa3 as Name | undefined)?.legacy) delete e.native.prusa3;
    setNative(target, e, 'prusa3', { key: id, ...pin });
  }

  // SuperSlicer.
  const s = PINNED.superslicer.files;
  const sTokens = tokenize(src.superslicer.printConfig);
  const sDefs = extractDefs(sTokens);
  const sMaps = enumMaps(sTokens);
  const known = (k: string) => sDefs.has(k);
  const ui = new Map<string, UiPlace>();
  const lists = { print: new Set<string>(), filament: new Set<string>(), printer: new Set<string>() };
  for (const [f, list] of [
    ['print', 'print'],
    ['filament', 'filament'],
    ['filamentOverride', 'filament'],
    ['printer', 'printer'],
    ['extruder', 'printer'],
  ] as const)
    for (const [k, place] of uiSettings(src.superslicer[f], s[f], known)) {
      if (!ui.has(k)) ui.set(k, place);
      lists[list].add(k);
    }
  const sPlace: Placement = { ...lists, perExtruder: new Set(stringList(sTokens, 'm_extruder_option_keys')) };
  for (const k of [...Object.keys(SUPERSLICER_RENAMES), ...Object.keys(SUPERSLICER_ORCA)])
    if (!sDefs.has(k)) throw new Error(`${k}: not a SuperSlicer FFF key`);
  for (const [k, r] of Object.entries(SUPERSLICER_ORCA))
    if (!(r.to in orca.entries)) throw new Error(`${k}: ${r.to} is not an Orca key`);
  for (const d of sDefs.values()) {
    const rename = SUPERSLICER_RENAMES[d.key];
    if (rename && !of29.has(rename.prusa)) throw new Error(`${d.key}: ${rename.prusa} is not a PrusaSlicer 2.9 key`);
    if (rename && sDefs.has(rename.prusa)) throw new Error(`${d.key}: SuperSlicer also has ${rename.prusa}`);
    const own = SUPERSLICER_ORCA[d.key];
    const prusaKey = rename?.prusa ?? d.key;
    const target = rename ? of29.get(rename.prusa) : (own?.to ?? of29.get(d.key) ?? orcaTarget(d.key));
    if (target) {
      // A Prusa rename's note holds for SuperSlicer, which shares the Prusa semantics.
      const viaPrusa = !own && of29.get(prusaKey) === target ? PRUSA_RENAMES[prusaKey]?.lossy : undefined;
      const lossy =
        rename?.lossy ??
        own?.lossy ??
        viaPrusa?.replaceAll(/\bPrusa\b/g, 'SuperSlicer') ??
        typeLoss('SuperSlicer', typeOf(d, sMaps), target, entry(target)!.type);
      setNative(target, entry(target)!, 'superslicer', { key: d.key, ...(lossy ? { lossy } : {}) });
      continue;
    }
    const place = ui.get(d.key);
    // shortcut: a SuperSlicer graph (coGraph, coGraphs) is stored as its points (polygon), without its interpolation
    // mode or default; give it a type of its own if a converter needs the graph semantics.
    const graph = /^coGraphs?$/.test(d.co);
    const def = graph ? { ...d, co: d.co === 'coGraph' ? 'coPoints' : 'coPointsGroups', value: undefined } : d;
    const e = toEntry(def, sPlace, sMaps, `Ported from SuperSlicer@${SUPERSLICER_COMMIT}:${s.printConfig}`);
    // A key on a `.ui` page takes that page's group (PRF-18); one on no page keeps its nearest category, hidden.
    if (place) {
      Object.assign(e, uiGroup(place.file, place.page, place.group, d.key));
      delete e.hidden;
    } else e.hidden = true;
    superslicer.entries[unified('superslicer.', d.key)] = {
      ...e,
      native: { superslicer: { key: d.key } },
      native_only: 'superslicer',
      provenance: `${e.provenance!}${place ? `; GUI: ${place.file}:${place.line} (${place.page} > ${place.group})` : ''}`,
    };
  }
  for (const [key, g] of Object.entries(PRUSA_GROUPS)) {
    if (!prusa.entries[key]) throw new Error(`${key}: PRUSA_GROUPS names no prusa. entry`);
    Object.assign(prusa.entries[key], g);
  }
  return { orca: merged, prusa, superslicer };
};
