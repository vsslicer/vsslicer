export type Sources = { [D in keyof Pinned]: { [F in keyof Pinned[D]['files']]: string } };

/** The commit a checkout's HEAD points at (a detached hash, a loose ref or a packed ref). */
export const headCommit = (repo: string): string => {
  const git = join(repo, '.git');
  const head = readSource(git, join(git, 'HEAD'), 4096).trim();
  if (!head.startsWith('ref: ')) return head;
  const ref = head.slice(5);
  if (existsSync(join(git, ref))) return readSource(git, join(git, ref), 4096).trim();
  for (const line of readSource(git, join(git, 'packed-refs')).split('\n'))
    if (line.endsWith(` ${ref}`)) return line.slice(0, line.indexOf(' '));
  throw new Error(`${repo}: cannot resolve ${ref}`);
};

/** The pinned files of every dialect, refusing a checkout at another commit. */
export const readPinned = (repos = REPOS): Sources => {
  const out: { [d: string]: { [f: string]: string } } = {};
  for (const [dialect, p] of Object.entries(PINNED)) {
    const root = join(repos, p.repo);
    const commit = headCommit(root);
    if (!commit.startsWith(p.commit)) throw new Error(`${p.repo} is at ${commit}, not the pinned ${p.commit}`);
    out[dialect] = Object.fromEntries(Object.entries(p.files).map(([k, f]) => [k, readSource(root, join(root, f))]));
  }
  return out as Sources;
};

