/**
 * The cura. entries, the material table and the per-extruder list (cura.json), and `names`: the Cura name of each
 * Orca key Cura has, which generate.ts merges into orca.json as `native.cura`. `orca` is the in-memory Orca catalogue
 * the names are checked against.
 */
export const generateCura = (
  printer: string,
  extruder: string,
  xmlProfile: string,
  orca: Catalogue,
): CuraCatalogueFile & { names: { [unified: string]: NativeKey } } => {
  const fromPrinter = extractCura(printer, FDMPRINTER);
  const fromExtruder = extractCura(extruder, FDMEXTRUDER);
  // A key in both files is one setting: fdmextruder's node overrides fdmprinter's for the extruder stack.
  const settings = new Map<string, { first: CuraSetting; node: CuraNode; extruderLine?: number }>();
  for (const s of fromPrinter) settings.set(s.key, { first: s, node: s.node });
  for (const s of fromExtruder) {
    const had = settings.get(s.key);
    if (had) settings.set(s.key, { ...had, node: { ...had.node, ...s.node }, extruderLine: s.line });
    else settings.set(s.key, { first: s, node: s.node, extruderLine: s.line });
  }
  const perExtruder = (k: string) => {
    const s = settings.get(k)!;
    // `settable_per_extruder` defaults to true (Cura@5bea2f8:cura/CuraApplication.py:415).
    return s.extruderLine !== undefined || s.node.settable_per_extruder !== false;
  };

  const names: { [unified: string]: NativeKey } = {};
  const named = new Map<string, string>();
  const nameOf = (target: string, nk: NativeKey, curaKeys: string[]) => {
    if (!orca[target]) throw new Error(`${target}: no such Orca entry`);
    if (names[target]) throw new Error(`${target}: two Cura names`);
    for (const k of curaKeys) {
      if (!settings.has(k)) throw new Error(`${k}: no such Cura setting`);
      named.set(k, target);
    }
    // Cura resolves most settings per extruder; an Orca key that is not per extruder keeps one value.
    const lost = curaKeys.some(perExtruder) && !orca[target]!.per_extruder ? PER_EXTRUDER_LOSSY : undefined;
    names[target] = lost ? { ...nk, lossy: nk.lossy ? `${nk.lossy}; ${lost}` : lost } : nk;
  };
  for (const [cura, n] of Object.entries(CURA_NAMES))
    nameOf(
      n.orca,
      { key: cura, ...(n.conversion ? { conversion: n.conversion } : {}), ...(n.lossy ? { lossy: n.lossy } : {}) },
      [cura],
    );
  for (const [orca, keys] of Object.entries(CURA_SPLITS))
    nameOf(
      orca,
      { conversion: { kind: 'split', keys }, ...(SPLIT_LOSSY[orca] ? { lossy: SPLIT_LOSSY[orca] } : {}) },
      keys,
    );

  const entries: { [key: string]: CatalogueEntry } = {};
  for (const [key, { first, node, extruderLine }] of settings) {
    if (named.has(key)) continue;
    const curaType = node.type!;
    const t = TYPES[curaType];
    if (!t) throw new Error(`${key}: unknown Cura type ${curaType}`);
    let type = t.type;
    if (type === 'string' && /gcode|_code$/.test(key)) type = 'gcode';
    const enumOptions: EnumOption[] = Object.entries(node.options ?? {}).map(([value, label]) => ({ value, label }));
    if (type === 'enum' && enumOptions.length === 0) type = 'string';
    const min = bound(node.minimum_value);
    const max = bound(node.maximum_value);
    const value = defaultOf(node, curaType);
    // Cura's per-model settings (`settable_per_mesh`, default true at Cura@5bea2f8:cura/CuraApplication.py:413) can be
    // set on a model and on a modifier mesh; Cura has no height ranges or plates.
    const scope: OverrideScope[] = node.settable_per_mesh === false ? [] : ['object', 'part'];
    entries[`cura.${key}`] = {
      ...placeOf(key, first.category),
      type,
      ...(t.list ? { list: true } : {}),
      ...(perExtruder(key) ? { per_extruder: true } : {}),
      ...(node.unit ? { unit: node.unit } : {}),
      ...(type === 'enum' ? { enum: enumOptions } : {}),
      ...(min !== undefined ? { min } : {}),
      ...(max !== undefined ? { max } : {}),
      ...(value !== undefined ? { default: value } : {}),
      label: node.label || key,
      ...(node.description ? { tooltip: node.description } : {}),
      native: { cura: { key } },
      override_scope: scope,
      // Cura's command-line settings are on no settings page.
      ...(first.category === 'command_line_settings' ? { hidden: true } : {}),
      native_only: 'cura',
      provenance:
        `Ported from ${cite(first)}` +
        (extruderLine !== undefined && first.file !== FDMEXTRUDER
          ? `; Cura@${CURA_COMMIT}:${FDMEXTRUDER}:${extruderLine}`
          : ''),
    };
  }

  const unifiedOf = (cura: string): string => {
    if (!settings.has(cura)) throw new Error(`XML table names unknown Cura setting ${cura}`);
    return named.get(cura) ?? `cura.${cura}`;
  };
  const material: { [xml: string]: CuraMaterialKey } = {};
  const tables = {
    settings: pythonMap(xmlProfile, '__material_settings_setting_map'),
    properties: pythonMap(xmlProfile, '__material_properties_setting_map'),
    metadata: pythonMap(xmlProfile, '__material_metadata_setting_map'),
  };
  for (const r of tables.settings)
    material[`settings/${r.from}`] = {
      cura: r.to,
      setting: unifiedOf(r.to),
      provenance: `Cura@${CURA_COMMIT}:${XML_PROFILE}:${r.line}`,
    };
  // XML element path -> Cura setting, as XmlMaterialProfile reads `<properties>` and `<metadata>` (GUID is a
  // direct child of <metadata>, brand and material sit in <metadata><name>).
  const mirrored = new Map([
    ...tables.properties.map((r) => [`properties/${r.from}`, r] as const),
    ...tables.metadata.map((r) => [r.from === 'GUID' ? 'metadata/GUID' : `metadata/name/${r.from}`, r] as const),
  ]);
  for (const path of mirrored.keys())
    if (!XML_FIELDS[path]) throw new Error(`${path}: Cura maps it to a setting but XML_FIELDS has no field for it`);
  for (const [path, f] of Object.entries(XML_FIELDS)) {
    const r = mirrored.get(path);
    if (!r && !f.cite) throw new Error(`${path}: no source`);
    material[path] = {
      field: f.field,
      ...(r ? { cura: r.to } : {}),
      provenance: r ? `Cura@${CURA_COMMIT}:${XML_PROFILE}:${r.line}` : f.cite!,
    };
  }

  const keys = [...settings.keys()];
  return {
    notice: CURA_NOTICE,
    entries,
    names,
    per_extruder: keys.filter(perExtruder),
    material,
  };
};

