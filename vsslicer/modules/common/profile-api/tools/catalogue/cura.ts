/** A plain number bound; expression bounds (`machine_nozzle_size * 0.1`) are dropped, not evaluated. */
const bound = (v: unknown): number | undefined => {
  const n = typeof v === 'number' ? v : typeof v === 'string' && v.trim() !== '' ? Number(v) : NaN;
  return Number.isFinite(n) ? n : undefined;
};

/** `value` (a Python formula) wins over `default_value`, as in Cura, and is kept verbatim as `{expr}`. */
const defaultOf = (node: CuraNode, curaType: string): SettingValue | undefined => {
  if (typeof node.value === 'string') return { expr: node.value };
  if (node.value !== undefined) return node.value as SettingValue;
  const v = node.default_value;
  // `[int]` defaults are JSON list text ("[ ]"), extruder numbers are strings ("-1").
  if (curaType === '[int]' && typeof v === 'string') {
    try {
      return JSON.parse(v) as SettingValue;
    } catch {
      return v;
    }
  }
  if ((curaType === 'extruder' || curaType === 'optional_extruder') && typeof v === 'string' && bound(v) !== undefined)
    return Number(v);
  return v as SettingValue | undefined;
};

