import { allSchemas, entitySchemas, nativeKeys, type SourceFile } from '@vsslicer/profile-api';
import { Ajv2020 } from 'ajv/dist/2020.js';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, test } from 'vitest';
import { importPrusaIni, type PrusaNative } from '../../src/adapters/import/import.ts';
import { SUPERSLICER_ONLY_KEYS } from '../../src/adapters/import/superslicer-keys.ts';

const file = (path: string, text: string): SourceFile => ({ path, bytes: new TextEncoder().encode(text) });
const FIXTURE = readFileSync(join(import.meta.dirname, '../fixtures/ini/superslicer.ini'), 'utf8');
const VENDOR = '[vendor]\nname = T\nconfig_version = 1.0.0\n';
const PRINT = '[print:P]\nlayer_height = 0.2\n';

const ajv = new Ajv2020({ allErrors: true, strict: false });
for (const s of allSchemas) ajv.addSchema(s);
const SCHEMA = { vendor: 'vendor', printer: 'printer_model', print: 'process', filament: 'material' } as const;

describe('SuperSlicer dialect', () => {
  test('the 356 SuperSlicer-only keys are all accounted for', () => {
    expect(SUPERSLICER_ONLY_KEYS.size).toBe(356);
    const r = importPrusaIni([file('SuperSlicer.ini', FIXTURE)]);
    expect(r.diagnostics.filter((d) => d.severity !== 'info')).toEqual([]);
    expect(r.entities.map((e) => e.id)).toEqual(['SuperSlicerFixture', 'SS Printer', 'SS Print', 'SS Filament']);
    const seen = new Set<string>();
    for (const e of r.entities) {
      const n = r.native[e.id] as PrusaNative;
      expect(n.dialect, e.id).toBe('superslicer'); // the header line marks the whole file
      const validate = ajv.compile(entitySchemas[SCHEMA[n.kind as keyof typeof SCHEMA]]);
      expect(validate(e), `${e.id}: ${JSON.stringify(validate.errors)}`).toBe(true);
      const settings = (e as { settings?: object }).settings ?? {};
      const mapped = new Set(Object.keys(settings).flatMap((k) => nativeKeys('prusa', k)));
      for (const k of Object.keys(n.values)) {
        if (!SUPERSLICER_ONLY_KEYS.has(k)) continue;
        // each extra key is either converted into a setting or listed native-only, never silently dropped
        expect(mapped.has(k) || n.native_only.includes(k), k).toBe(true);
        seen.add(k);
      }
    }
    expect(seen.size).toBe(356);
  });

  test('dialect is detected from the header line or from an extra key, else prusa', () => {
    const dialect = (text: string) =>
      (importPrusaIni([file('a.ini', VENDOR + text)]).native['P'] as PrusaNative).dialect;
    expect(dialect(PRINT)).toBe('prusa');
    expect(dialect(PRINT + 'perimeter_loop = 1\n')).toBe('superslicer');
    const withHeader = importPrusaIni([file('a.ini', '# generated by SuperSlicer 2.7\n' + VENDOR + PRINT)]);
    expect((withHeader.native['P'] as PrusaNative).dialect).toBe('superslicer');
    const prusaHeader = importPrusaIni([file('a.ini', '# generated by PrusaSlicer 2.9\n' + VENDOR + PRINT)]);
    expect((prusaHeader.native['P'] as PrusaNative).dialect).toBe('prusa');
  });

  test('the header is searched only in the first bytes of a file', () => {
    const late = '#' + ' '.repeat(600) + '\n# generated by SuperSlicer\n';
    const r = importPrusaIni([file('a.ini', late + VENDOR + PRINT)]);
    expect((r.native['P'] as PrusaNative).dialect).toBe('prusa');
  });
});
