/** Bytes over all files of one call; one pinned bundle is 1.5 MB. */
export const MAX_IMPORT_BYTES = 256 * 1024 * 1024;
/** Sections over all files of one call; the pinned bundle has 6 976. Files past the cap are not read. */
export const MAX_IMPORT_SECTIONS = 100_000;
/** Keys copied from parents over one call; the pinned bundle needs 476 151. */
export const MAX_INHERITED_KEYS = 1_000_000;

/** The native form kept beside each entity in `ImportResult.native`, for round trips. */
export interface PrusaNative {
  format: 'prusa-ini';
  kind: Exclude<IniSectionKind, 'root' | 'other'>;
  /** Section name (`0.20mm SPEED @MK4S 0.4`); the `[vendor]` section has none. */
  name: string;
  file: string;
  line: number;
  /**
   * `superslicer` when the file's first lines say `generated by SuperSlicer` or a key only SuperSlicer defines is present.
   * SuperSlicer-only keys have no unified home yet, so they stay in `values` and `native_only`.
   */
  dialect: 'prusa' | 'superslicer';
  /** Every key after flattening, verbatim. */
  values: Record<string, string>;
  /** Keys with no unified home: not converted into `settings` or an entity field. They round-trip from `values`. */
  native_only: string[];
}

const PRESET_KINDS = ['printer', 'print', 'filament'] as const;
type PresetKind = (typeof PRESET_KINDS)[number];

let reverse: Map<string, string[]> | undefined;
/** Prusa native key -> unified keys spanning it, from profile-api's mapped keys. */
function unifiedOf(native: string): string[] {
  if (!reverse) {
    reverse = new Map();
    for (const key of MAPPED_KEYS) {
      let natives: string[];
      try {
        natives = nativeKeys('prusa', key);
      } catch {
        continue; // no Prusa equivalent
      }
      for (const n of natives) reverse.set(n, [...(reverse.get(n) ?? []), key]);
    }
  }
  return reverse.get(native) ?? [];
}

/** Bytes of a file searched for the `# generated by SuperSlicer` header line (Config.cpp:2080 of SuperSlicer@1f3d287 writes it first). */
const HEADER_BYTES = 512;
const SS_HEADER = /^[#;] *generated by SuperSlicer/im;
const headerIsSuperSlicer = (bytes: Uint8Array) =>
  SS_HEADER.test(new TextDecoder().decode(bytes.subarray(0, HEADER_BYTES)));

interface Ctx {
  file: string;
  superslicer: boolean;
  vendor: string;
  diag: Diag;
}

/** Converts every mapped key; returns the settings and the native keys they consumed. */
function toSettings(values: Map<string, string>, line: (key: string) => number, ctx: Ctx) {
  const settings: Settings = {};
  const used = new Set<string>();
  for (const native of values.keys()) {
    for (const key of unifiedOf(native)) {
      if (key in settings) continue;
      const natives = nativeKeys('prusa', key);
      if (!natives.every((n) => values.get(n))) continue; // an empty value is unset; it stays native
      try {
        const r = nativeToUnified('prusa', key, Object.fromEntries(natives.map((n) => [n, values.get(n)!])));
        // per-extruder values are keyed maps in the schema; the mapping returns a single point as an array
        settings[key] = orcaCatalogue.entries[key]?.per_extruder && Array.isArray(r.value) ? { '0': r.value } : r.value;
        for (const n of natives) used.add(n);
      } catch (e) {
        ctx.diag(
          'info', // the value stays in the native form; profile-api maps one value, not per-extruder lists
          'malformed-line',
          line(native),
          `${native}: no unified value (${(e as Error).message.slice(0, 200)}); kept native`,
        );
      }
    }
  }
  return { settings, used };
}

const num = (v: string | undefined) => (v === undefined || v.trim() === '' ? NaN : Number(v.split(',')[0]));

/** Maps one flattened section; undefined (with a diagnostic) when a required field is missing. */
function toEntity(
  f: Flattened,
  kind: PresetKind | 'vendor' | 'printer_model',
  ctx: Ctx,
  /** `[printer_model]` id -> its first printer preset */
  printers: ReadonlyMap<string, PrinterModel>,
) {
  const { section, values } = f;
  const line = (key: string) => section.entries.find((e) => e.key === key)?.line ?? section.line;
  const consumed = new Set<string>();
  const take = (key: string) => {
    consumed.add(key);
    return values.get(key);
  };
  const missing = (what: string) => {
    ctx.diag(
      'error',
      'malformed-line',
      section.line,
      `[${kind}${section.name ? `:${section.name}` : ''}] has no ${what}; not imported`,
    );
    return undefined;
  };
  const base = () => {
    const out: { id: string; inherits?: string[]; renamed_from?: string[]; when?: string } = { id: section.name };
    take('inherits');
    if (f.inherits.length) out.inherits = f.inherits;
    const ren = take('renamed_from');
    if (ren !== undefined) {
      const names = splitList(ren);
      if (names?.length) out.renamed_from = names;
      else ctx.diag('warning', 'malformed-line', line('renamed_from'), 'invalid renamed_from; kept native');
    }
    const cond = values.get('compatible_printers_condition');
    const printers = values.get('compatible_printers');
    // upstream applies the condition only when the list is empty (PrusaSlicer@b028299:src/libslic3r/Preset.cpp:396-410)
    if (cond && printers && splitList(printers)?.length !== 0)
      ctx.diag(
        'info',
        'malformed-line',
        line('compatible_printers_condition'),
        'compatible_printers is set, so PrusaSlicer ignores compatible_printers_condition; kept native',
      );
    else if (cond) {
      const c = convertPrusaCondition(cond);
      if (c.expression !== null) {
        out.when = c.expression;
        consumed.add('compatible_printers_condition');
      } else
        ctx.diag(
          'warning',
          'malformed-line',
          line('compatible_printers_condition'),
          `condition not converted: ${c.diagnostics.join('; ').slice(0, 300)}`,
        );
    }
    return out;
  };

  let entity: ImportedEntity | undefined;
  let used = new Set<string>();
  if (kind === 'vendor') {
    const name = take('name');
    const version = take('config_version');
    if (!name) return missing('name');
    if (!version) return missing('config_version');
    // the bundle states no licence; PrusaSlicer ships it in an AGPL-3.0 repository (profiles.md, licence notes)
    entity = { id: take('repo_id') || name, name, version, license: 'NOASSERTION' } satisfies Vendor;
  } else if (kind === 'printer_model') {
    // the bed and toolheads live on the per-nozzle printer presets: take them from the first of this model
    const first = printers.get(section.name);
    if (!first) return missing('printer preset of this model');
    const name = take('name');
    const tech = take('technology');
    if (tech && tech !== 'FFF') return missing('FFF technology');
    const m: PrinterModel = {
      id: section.name,
      vendor: ctx.vendor,
      name: name || section.name,
      technology: 'fff',
      bed: first.bed,
      toolheads: first.toolheads,
    };
    const family = take('family');
    if (family) m.family = family;
    const assets = Object.fromEntries(
      (['bed_model', 'bed_texture', 'thumbnail'] as const).flatMap((k) => (values.has(k) ? [[k, take(k)!]] : [])),
    );
    if (Object.keys(assets).length) m.assets = assets;
    const mats = take('default_materials');
    if (mats)
      m.defaults = {
        materials: mats
          .split(';')
          .map((s) => s.trim())
          .filter(Boolean),
      };
    entity = m;
  } else {
    const s = toSettings(values, line, ctx);
    used = s.used;
    const b = base();
    if (kind === 'printer') {
      if (take('printer_technology') === 'SLA') return missing('FFF technology');
      if (!Array.isArray(s.settings['printable_area'])) return missing('usable bed_shape');
      const nozzles = values.get('nozzle_diameter')?.split(',').length ?? 0;
      if (!nozzles) return missing('nozzle_diameter');
      const height = typeof s.settings['printable_height'] === 'number' ? s.settings['printable_height'] : 0;
      const notes = values.get('printer_notes');
      if (notes) {
        // `printer_notes =~` keyword tests convert to `'TAG' in printer.tags`; the notes text itself stays native
        const t = noteTags(notes);
        if (t.tags.length) s.settings['tags'] = t.tags;
        for (const k of t.unknown)
          ctx.diag(
            'warning',
            'unknown-type',
            line('printer_notes'),
            `printer_notes keyword ${k.slice(0, 100)} is not in the tag table; not tagged`,
          );
      }
      const m: PrinterModel = {
        ...b,
        vendor: ctx.vendor,
        name: section.name,
        technology: 'fff',
        bed: { shape: s.settings['printable_area'] as [number, number][], max_height: height },
        // PrusaSlicer has no kinematics setting
        toolheads: { count: nozzles, kinematics: 'unspecified' },
        settings: s.settings,
      };
      const model = take('printer_model');
      if (model) m.family = model; // the [printer_model] id; `splitVariants` turns the preset into a nozzle of it
      const proc = take('default_print_profile');
      const fil = take('default_filament_profile');
      if (proc || fil) {
        m.defaults = {
          ...(proc ? { process: proc } : {}),
          ...(fil ? { materials: (splitList(fil) ?? [fil]).filter(Boolean) } : {}),
        };
      }
      entity = m;
    } else if (kind === 'print') {
      const lh = s.settings['layer_height'];
      if (typeof lh !== 'number' || !(lh > 0)) return missing('positive layer_height');
      entity = { ...b, name: section.name, layer_height: lh, settings: s.settings } satisfies Process;
    } else {
      const type = s.settings['filament_type'];
      const dia = num(values.get('filament_diameter'));
      if (typeof type !== 'string' || !type) return missing('filament_type');
      if (!(dia > 0)) return missing('positive filament_diameter');
      entity = {
        ...b,
        vendor: ctx.vendor,
        name: section.name,
        type,
        diameter: dia,
        external_ids: { prusa_name: section.name },
        settings: s.settings,
      } satisfies Material;
    }
  }
  const native: PrusaNative = {
    format: 'prusa-ini',
    kind,
    name: section.name,
    file: ctx.file,
    line: section.line,
    dialect: ctx.superslicer || [...values.keys()].some((k) => SUPERSLICER_ONLY_KEYS.has(k)) ? 'superslicer' : 'prusa',
    values: Object.fromEntries(values),
    native_only: [...values.keys()].filter((k) => !used.has(k) && !consumed.has(k)),
  };
  return { entity, native };
}

/** A section that inherits nothing, first value of a key winning as in `flattenKind`. */
function own(section: IniSection): Flattened {
  const values = new Map<string, string>();
  for (const e of section.entries) if (!values.has(e.key)) values.set(e.key, e.value);
  return { section, values, inherits: [] };
}

/** `print/My PLA.ini` -> print; a user preset file has no header, so its folder names the kind (as PrusaSlicer stores them). */
function kindOfPath(path: string): PresetKind | undefined {
  const parts = path.split(/[\\/]/);
  const dir = parts.at(-2);
  return PRESET_KINDS.find((k) => k === dir);
}

/**
 * Imports PrusaSlicer 2.9 INI files: vendor bundles (`[vendor]` + sections) and user presets (header-less files
 * under `print/`, `filament/`, `printer/`, or config bundles). Each file is flattened on its own, as upstream does.
 * Vendor bundles lose `inherits`; user presets keep the names of parents outside their file. Entity ids are the
 * section names (the `[printer_model]` id for a model). Per-nozzle printer presets of a bundle become `nozzle`
 * entities of their `[printer_model]` (`splitVariants`); `{ splitVariants: false }` keeps them as one
 * printer_model each. Never throws on bad input.
 */
export function importPrusaIni(files: readonly SourceFile[], options: { splitVariants?: boolean } = {}): ImportResult {
  const result: ImportResult = { entities: [], native: {}, diagnostics: [] };
  const push = (d: Diagnostic) => {
    const n = result.diagnostics.length;
    if (n > MAX_DIAGNOSTICS) return;
    result.diagnostics.push(
      n === MAX_DIAGNOSTICS ? { ...d, severity: 'warning', message: 'further diagnostics suppressed' } : d,
    );
  };
  const budget: Budget = { copies: 0, max: MAX_INHERITED_KEYS };
  let bytes = 0;
  let sectionCount = 0;
  for (const file of files) {
    const fileDiag: Diag = (severity, code, line, message) => push({ severity, code, file: file.path, line, message });
    bytes += file.bytes.byteLength;
    if (bytes > MAX_IMPORT_BYTES) {
      push({
        severity: 'error',
        code: 'malformed-line',
        file: file.path,
        message: `import over ${MAX_IMPORT_BYTES} bytes; this and later files not read`,
      });
      break;
    }
    const doc = parseIni(file.bytes, file.path);
    doc.diagnostics.forEach(push);
    sectionCount += doc.sections.length;
    if (sectionCount > MAX_IMPORT_SECTIONS) {
      push({
        severity: 'error',
        code: 'malformed-line',
        file: file.path,
        message: `import over ${MAX_IMPORT_SECTIONS} sections; this and later files not read`,
      });
      break;
    }
    const sections: IniSection[] = [];
    for (const s of doc.sections) {
      if (s.kind !== 'root') sections.push(s);
      else {
        const kind = kindOfPath(file.path);
        if (kind)
          sections.push({
            ...s,
            kind,
            name: file.path
              .split(/[\\/]/)
              .at(-1)!
              .replace(/\.ini$/i, ''),
          });
        else
          fileDiag(
            'error',
            'unknown-type',
            s.line,
            'keys outside a section, and the folder is not print/, filament/ or printer/; not imported',
          );
      }
    }
    const vendorSection = sections.find((s) => s.kind === 'vendor');
    const ctx: Ctx = {
      file: file.path,
      superslicer: doc.sections.length > 0 && headerIsSuperSlicer(file.bytes),
      vendor: 'user',
      diag: fileDiag,
    };
    const add = (r: Mapped) => {
      if (!r) return;
      if (Object.hasOwn(result.native, r.entity.id)) {
        fileDiag(
          'warning',
          'malformed-line',
          r.native.line,
          `id "${r.entity.id.slice(0, 256)}" already imported; this one skipped`,
        );
        return;
      }
      result.entities.push(r.entity);
      // an own key even for ids like `__proto__` (section names are untrusted)
      Object.defineProperty(result.native, r.entity.id, {
        value: r.native,
        enumerable: true,
        writable: true,
        configurable: true,
      });
    };
    if (vendorSection) {
      const v = toEntity(own(vendorSection), 'vendor', ctx, new Map());
      if (v) {
        ctx.vendor = v.entity.id;
        add(v);
      }
    }
    const flat = Object.fromEntries(
      PRESET_KINDS.map((k) => [
        k,
        flattenKind(
          sections.filter((s) => s.kind === k),
          !!vendorSection,
          budget,
          fileDiag,
        ),
      ]),
    ) as Record<PresetKind, Flattened[]>;
    const printers = new Map<string, PrinterModel>();
    const mapped = PRESET_KINDS.map((k) => flat[k].map((f) => toEntity(f, k, ctx, printers)));
    for (const r of mapped[0]!) {
      const p = r?.entity as PrinterModel | undefined;
      if (p?.family && !printers.has(p.family)) printers.set(p.family, p);
    }
    const all = [
      ...sections
        .filter((s) => s.kind === 'printer_model')
        .map((s) => toEntity(own(s), 'printer_model', ctx, printers)),
      ...mapped.flat(),
    ].filter((r) => r !== undefined);
    // PrusaSlicer keeps models, printers, prints and filaments in separate collections, so one name can be several
    // kinds (Sovol's [printer_model:SV06] and [printer:SV06]): a name another kind already holds gets `<kind>:<name>`.
    // Done before the split so a nozzle's id, its override condition and its model's `nozzles` agree.
    const kinds = new Map<string, string>();
    for (const r of all) {
      const id = r.entity.id;
      const taken = Object.hasOwn(result.native, id) ? (result.native[id] as PrusaNative).kind : kinds.get(id);
      if (taken !== undefined && taken !== r.native.kind) r.entity.id = `${r.native.kind}:${id}`;
      else kinds.set(id, r.native.kind);
    }
    (options.splitVariants === false ? all : splitVariants(all, fileDiag)).forEach(add);
  }
  return result;
}

export const prusaIniImporter: Importer = {
  formats: ['prusa-ini'],
  canHandle: (file) => /\.ini$/i.test(file.path),
  import: async (files) => importPrusaIni(files),
};
