import { BlockType, MetadataEncoding, type BgcodeDiagnostic } from '../domain/bgcode.ts';
import {
  bytesToLatin1,
  dropBlankLines,
  latin1ToBytes,
  entriesText,
  parseIni,
  thumbnailText,
  type BgcodeMetadata,
  type MetadataEntries,
  type Thumbnail,
} from '../domain/ascii.ts';
import type { GcodeEvent } from './read-gcode.ts';

export type ToGcodeEvent =
  | { kind: 'text'; text: Uint8Array }
  | { kind: 'metadata'; metadata: BgcodeMetadata }
  | { kind: 'diagnostic'; diagnostic: BgcodeDiagnostic };

const utf8 = new TextEncoder();
const utf8Dec = new TextDecoder();

/**
 * Turns a `decodeGcodeBlocks` stream into the text of the `.gcode` twin (`text` chunks, concatenate
 * them) plus one final `metadata` event with every metadata block and the thumbnails.
 * Layout as libbgcode's converter writes it: generator line, printer metadata, thumbnails, the
 * G-code (blank lines dropped), print metadata, then the Slicer3 JSON and legacy slicer config.
 */
export async function* bgcodeToGcode(events: AsyncIterable<GcodeEvent>): AsyncGenerator<ToGcodeEvent> {
  let file: MetadataEntries = [];
  let printer: MetadataEntries = [];
  let print: MetadataEntries = [];
  let slicer: MetadataEntries = [];
  let slicerJson: string | undefined;
  const thumbnails: Thumbnail[] = [];
  let headDone = false;
  const head = (): ToGcodeEvent => {
    headDone = true;
    const get = (k: string) => file.find(([key]) => key === k)?.[1];
    let gen = get('Producer') ?? 'Unknown';
    if (get('Produced on') !== undefined) gen += ` on ${get('Produced on')}`;
    if (get('Prepared by') !== undefined) gen += `\n; prepared by ${get('Prepared by')}`;
    const t =
      (file.length ? `; generated by ${gen}\n\n\n` : '') +
      entriesText(printer) +
      thumbnails.map(thumbnailText).join('') +
      '\n';
    return { kind: 'text', text: utf8.encode(t) };
  };

  for await (const e of events) {
    if (e.kind === 'diagnostic') yield e;
    else if (e.kind === 'gcode') {
      if (!headDone) yield head();
      const t = dropBlankLines(bytesToLatin1(e.text));
      if (t) yield { kind: 'text', text: latin1ToBytes(t) };
    } else if (e.kind === 'block' && e.block.data) {
      const { block } = e;
      const data = block.data!;
      if (block.params.type === 5)
        thumbnails.push({ format: block.params.format, width: block.params.width, height: block.params.height, data });
      else if (block.type === BlockType.FileMetadata) file = parseIni(data);
      else if (block.type === BlockType.PrinterMetadata) printer = parseIni(data);
      else if (block.type === BlockType.PrintMetadata) print = parseIni(data);
      else if (block.type === BlockType.SlicerMetadata) {
        if (block.params.encoding === MetadataEncoding.Json) slicerJson = utf8Dec.decode(data);
        else slicer = parseIni(data);
      }
    }
  }
  if (!headDone) yield head();
  const tail =
    '\n' +
    entriesText(print) +
    (slicerJson === undefined
      ? ''
      : `\n; prusaslicer_json_config = begin\n; ${slicerJson}\n; prusaslicer_json_config = end\n`) +
    (slicer.length ? `\n; prusaslicer_config = begin\n${entriesText(slicer)}; prusaslicer_config = end\n\n` : '');
  yield { kind: 'text', text: utf8.encode(tail) };
  yield { kind: 'metadata', metadata: { file, printer, print, slicer, slicerJson, thumbnails } };
}
