import { MoveRole } from '@vsslicer/gcode-api';
import type { Slicer } from '@vsslicer/gcode-api';
import type { ChunkWriter } from './chunk-writer.ts';
import type { Machine } from './machine.ts';
import { flavourFromName, ROLE_BY_NAME, SLICER_BY_NAME } from './tag-tables.ts';

const SEMICOLON = 0x3b;
const SPACE = 0x20;
const TAB = 0x09;
/** The producer is named in the first lines (a PrusaSlicer thumbnail block follows them): look this far, in comment lines. */
const HEADER_COMMENTS = 100;
/** Distinct unknown role names reported; a file full of them would otherwise flood the diagnostics. */
const MAX_UNKNOWN_ROLES = 8;

const decoder = new TextDecoder('utf-8');

/** Index after `text` if `buf[i..end)` starts with it (ASCII only), else -1. No allocation. */
function after(buf: Uint8Array, i: number, end: number, text: string): number {
  if (i + text.length > end) return -1;
  for (let k = 0; k < text.length; k++) if (buf[i + k] !== text.charCodeAt(k)) return -1;
  return i + text.length;
}

const isBlank = (c: number | undefined): boolean => c === SPACE || c === TAB;
const rest = (buf: Uint8Array, i: number, end: number): string => decoder.decode(buf.subarray(i, end)).trim();

/**
 * Reads the slicers' own comments: who made the file and for which firmware (header lines and the
 * config block), the role of the extrusions that follow (`;TYPE:`, `; FEATURE:`) and where a layer
 * starts (`;LAYER_CHANGE`, `; CHANGE_LAYER`, `;LAYER:`) with its z (`;Z:`, `; Z_HEIGHT:`). The tag
 * sets of all slicers are read at once: the names and tags do not collide, so the detected slicer
 * only decides what the chunks report. Whole-line comments only, as the slicers write them.
 *
 * `;MESH:` (Cura) names the object; there is nowhere to store it yet, so it is ignored.
 */
export class SlicerTags {
  slicer: Slicer = 'unknown';
  /** The last flavour name the file stated (`;FLAVOR:`, `; gcode_flavor =`), even when an option fixed the flavour. */
  flavourName: string | undefined;
  private readonly out: ChunkWriter;
  private readonly machine: Machine;
  /** An explicit `flavour` option beats the detected one. */
  private readonly flavourFixed: boolean;
  private comments = 0;
  private roleTags = 0;
  private layerTags = 0;
  private readonly unknownRoles = new Set<string>();

  constructor(out: ChunkWriter, machine: Machine, flavourFixed: boolean) {
    this.out = out;
    this.machine = machine;
    this.flavourFixed = flavourFixed;
  }

  /** `buf[0, end)` is one line without its line break. Non-comment lines are ignored. */
  handle(buf: Uint8Array, end: number, fileOffset: number): void {
    let i = 0;
    while (i < end && isBlank(buf[i])) i++;
    if (buf[i] !== SEMICOLON) return;
    i++;
    while (i < end && isBlank(buf[i])) i++;
    this.comments++;
    let n: number;
    switch (buf[i]) {
      case 0x54: // T
        if ((n = after(buf, i, end, 'TYPE:')) >= 0) this.role(rest(buf, n, end), fileOffset);
        return;
      case 0x46: // F
        if ((n = after(buf, i, end, 'FEATURE:')) >= 0) this.role(rest(buf, n, end), fileOffset);
        else if ((n = after(buf, i, end, 'FLAVOR:')) >= 0) {
          this.flavour(rest(buf, n, end));
          this.detect('cura');
        }
        return;
      case 0x4c: // L
        if ((n = after(buf, i, end, 'LAYER_CHANGE')) >= 0 && rest(buf, n, end) === '') this.layer();
        else if (after(buf, i, end, 'LAYER:') >= 0) this.layer();
        return;
      case 0x43: // C
        if ((n = after(buf, i, end, 'CHANGE_LAYER')) >= 0 && rest(buf, n, end) === '') this.layer();
        return;
      case 0x45: // E: klipper_estimator macro time (klipper_estimator@dbcff4a:lib/src/planner.rs:171-178)
        if ((n = after(buf, i, end, 'ESTIMATOR_ADD_TIME')) >= 0 && isBlank(buf[n])) {
          const word = rest(buf, n, end).split(/\s/, 1)[0] ?? '';
          const seconds = word === '' ? NaN : Number(word);
          if (Number.isFinite(seconds) && seconds >= 0) this.out.marker('ESTIMATOR_ADD_TIME', fileOffset, seconds);
        }
        return;
      case 0x5a: // Z
        if ((n = after(buf, i, end, 'Z_HEIGHT:')) >= 0 || (n = after(buf, i, end, 'Z:')) >= 0) {
          const z = Number(rest(buf, n, end));
          if (!Number.isNaN(z)) this.out.layerZ(z);
        }
        return;
      case 0x67: // g
        if ((n = after(buf, i, end, 'gcode_flavor')) >= 0) {
          const eq = rest(buf, n, end);
          if (eq.startsWith('=')) this.flavour(eq.slice(1).trim());
        } else if ((n = after(buf, i, end, 'generated by ')) >= 0 && this.comments <= HEADER_COMMENTS) {
          this.detect(SLICER_BY_NAME.get(rest(buf, n, end).split(/\s/, 1)[0] ?? '') ?? 'unknown');
        }
        return;
      case 0x42: // B
        if (after(buf, i, end, 'BambuStudio ') >= 0 && this.comments <= HEADER_COMMENTS) this.detect('bambustudio');
        return;
      case 0x47: // G
        if (after(buf, i, end, 'Generated with Cura_SteamEngine') >= 0 && this.comments <= HEADER_COMMENTS)
          this.detect('cura');
        return;
    }
  }

  /** At the end of the file: one diagnostic if the slicer tags were missing. */
  finish(fileOffset: number): void {
    if (this.out.nextMove === 0 || (this.roleTags > 0 && this.layerTags > 0)) return;
    const missing =
      this.roleTags === 0 && this.layerTags === 0
        ? 'role tags (;TYPE: / ; FEATURE:) and layer tags (;LAYER_CHANGE / ; CHANGE_LAYER / ;LAYER:)'
        : this.roleTags === 0
          ? 'role tags (;TYPE: / ; FEATURE:)'
          : 'layer tags (;LAYER_CHANGE / ; CHANGE_LAYER / ;LAYER:)';
    const effect = this.roleTags === 0 ? 'moves have role unknown' : 'the layer list is empty';
    this.out.diagnostic(
      'no-slicer-tags',
      'info',
      fileOffset,
      `no ${missing} found (detected slicer: ${this.slicer}); ${effect}`,
    );
  }

  private detect(slicer: Slicer): void {
    if (this.slicer === 'unknown') this.slicer = slicer;
  }

  private flavour(name: string): void {
    if (name !== '') this.flavourName = name;
    if (!this.flavourFixed) this.machine.flavour = flavourFromName(name);
  }

  private layer(): void {
    this.layerTags++;
    this.out.layerChange();
  }

  private role(name: string, fileOffset: number): void {
    this.roleTags++;
    const role = ROLE_BY_NAME.get(name);
    this.out.role = role ?? MoveRole.Unknown;
    if (role === undefined && !this.unknownRoles.has(name) && this.unknownRoles.size < MAX_UNKNOWN_ROLES) {
      this.unknownRoles.add(name);
      this.out.diagnostic(
        'unknown-role',
        'warning',
        fileOffset,
        `role tag "${name}" is not known; moves have role unknown`,
      );
    }
  }
}
